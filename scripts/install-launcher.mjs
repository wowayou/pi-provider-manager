// Installing the launcher used to be a two-operand `install` command copied out
// of the README, with a destination the reader had to get right and a working
// directory the command never stated. Run from anywhere else it fails with GNU
// install's own "missing destination file operand", which names neither this
// project nor the mistake. There is nothing left to type.
//
// It installs a shim rather than a copy, because a copy is the bug this project
// already shipped once: a pre-0.3.0 launcher still starts, it just stops handing
// the Codex directory and the LiteLLM path to the detached server, so the
// managed bridge fails with no visible connection to the launcher that caused
// it. A shim execs whatever is in the checkout right now, so updating the
// checkout is the whole upgrade.

import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

// Both the shim and every generation of the real launcher contain this, so it
// answers "is the file already at the destination one of ours?" without needing
// to know which generation it is.
const OURS = "PI_PROVIDER_MANAGER_";
const SHIM_MARKER = "pi-provider-manager-ui shim";

// JSON quoting is not bash quoting: a checkout path containing `$` or a backtick
// would be expanded inside double quotes. Single quotes expand nothing, so the
// only character needing an escape is the quote itself.
const singleQuote = (value) => `'${value.replaceAll("'", "'\\''")}'`;

export function shimSource(target) {
  return [
    "#!/usr/bin/env bash",
    `# ${SHIM_MARKER} — generated by 'npm run install:launcher'. Safe to delete.`,
    "#",
    "# This is deliberately not a copy of the launcher. It execs the one in the",
    "# checkout named below, so pulling that checkout upgrades this command too.",
    "set -euo pipefail",
    "",
    `project_dir=${singleQuote(target)}`,
    'launcher="$project_dir/bin/pi-provider-manager-ui"',
    "",
    'if [[ ! -x "$launcher" ]]; then',
    '  echo "Pi Provider Manager is no longer at: $project_dir" >&2',
    '  echo "Its checkout moved or was deleted. Re-run \'npm run install:launcher\' from the new one," >&2',
    `  echo "or delete this shim: $\{BASH_SOURCE[0]}" >&2`,
    "  exit 1",
    "fi",
    "",
    "# Only as a default: an explicit override still wins, which is what makes",
    "# this shim usable against a second checkout without reinstalling.",
    'export PI_PROVIDER_MANAGER_PROJECT_DIR="${PI_PROVIDER_MANAGER_PROJECT_DIR:-$project_dir}"',
    'exec "$launcher" "$@"',
    "",
  ].join("\n");
}

export function installLauncher({ force = false, home = os.homedir(), env = process.env } = {}) {
  if (process.platform === "win32") {
    throw new Error(
      "There is no established place to install a PowerShell launcher, so this command does not guess.\n" +
      `Run it from the checkout instead: pwsh -File ${path.join(projectRoot, "bin", "pi-provider-manager.ps1")}`,
    );
  }

  // The launcher writes its log into the Pi agent directory, so the launcher
  // belongs beside it. Honouring the override keeps a throwaway
  // PI_CODING_AGENT_DIR genuinely throwaway.
  // Resolved, because a relative PI_CODING_AGENT_DIR would otherwise install
  // relative to whatever directory npm happened to run in and report that
  // relative path back as though it were where the command now lives.
  const agentDir = path.resolve(env.PI_CODING_AGENT_DIR || path.join(home, ".pi", "agent"));
  const binDir = path.join(agentDir, "bin");
  const destination = path.join(binDir, "pi-provider-manager-ui");

  let replaced = null;
  if (fs.existsSync(destination)) {
    const existing = fs.readFileSync(destination, "utf8");
    if (!existing.includes(OURS) && !force) {
      throw new Error(
        `Something that is not a Pi Provider Manager launcher is already at:\n  ${destination}\n` +
        "Nothing was changed. Pass --force to replace it.",
      );
    }
    replaced = existing.includes(SHIM_MARKER) ? "shim" : "copy";
  }

  fs.mkdirSync(binDir, { recursive: true });
  // 0700 matches what this project writes everywhere else, and the shim names a
  // path in the user's home directory, so it is not world-readable either.
  fs.writeFileSync(destination, shimSource(projectRoot), { mode: 0o700 });
  fs.chmodSync(destination, 0o700);
  return { destination, projectRoot, replaced };
}

// Windows has no established place to put a launcher, so nothing is installed
// there and nothing is guessed. As a *command* that is a successful no-op rather
// than a failure — `npm run setup` has by then already installed and built, and
// exiting non-zero would report that whole sequence as broken. installLauncher()
// itself still refuses, so a caller cannot mistake the no-op for an install.
function windowsGuidance() {
  process.stdout.write(
    "Nothing installed: Windows has no established place for a launcher, so this command does not guess.\n" +
    `Everything else is ready. Start it from the checkout:\n  pwsh -File ${path.join(projectRoot, "bin", "pi-provider-manager.ps1")}\n`,
  );
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  // `npm run install:launcher | head -1` closes the pipe mid-write, and the
  // default reaction to that is an unhandled EPIPE and a stack trace on a
  // command that in fact succeeded.
  process.stdout.on("error", () => {});
  if (process.platform === "win32") {
    windowsGuidance();
    process.exit(0);
  }
  try {
    const { destination, projectRoot: target, replaced } = installLauncher({
      force: process.argv.includes("--force"),
    });
    const what = replaced === "copy"
      ? "Replaced an older launcher copy with a shim"
      : replaced === "shim" ? "Updated the shim" : "Installed";
    process.stdout.write(`${what}: ${destination}\n`);
    process.stdout.write(`  runs: ${target}\n`);
    if (!fs.existsSync(path.join(target, "dist", "client", "index.html"))) {
      process.stdout.write("  build it first: npm run build\n");
    }
    process.stdout.write(`\nStart it with:\n  ${destination}\n`);
  } catch (error) {
    process.stderr.write(`${error.message}\n`);
    process.exit(1);
  }
}
